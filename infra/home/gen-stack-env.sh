#!/usr/bin/env bash
# Write infra/home/stack.env: the Portainer stack's variables with freshly generated secrets.
#
#   ./infra/home/gen-stack-env.sh                 # bymile.site
#   DOMAIN=example.com ./infra/home/gen-stack-env.sh
#
# The file is gitignored and is the only copy of these secrets: keep it (a password manager is a
# good place). It refuses to overwrite an existing file, because the database volumes keep the
# old passwords: new ones would lock the stack out of its own data.
set -euo pipefail

OUT="$(cd "$(dirname "$0")" && pwd)/stack.env"
DOMAIN="${DOMAIN:-bymile.site}"

if [[ -e "$OUT" ]]; then
  echo "$OUT already exists; not overwriting it (see the comment at the top of this script)." >&2
  exit 1
fi

hex() { openssl rand -hex "$1"; }   # letters and digits only: safe in URLs, JSON and env files

umask 077
cat > "$OUT" <<ENV
# Generated by gen-stack-env.sh on $(date +%Y-%m-%d). Contains secrets: never commit or paste it.
IMAGE_PREFIX=docker.io/paulleebm
IMAGE_TAG=latest
DOMAIN=${DOMAIN}
PUBLIC_SCHEME=https
APP_HOST=app.${DOMAIN}
AUTH_HOST=auth.${DOMAIN}
FILES_HOST=files.${DOMAIN}
INBOX_HOST=inbox.${DOMAIN}
STORAGE_CAPACITY_GB=100

POSTGRES_PASSWORD=$(hex 20)
LMS_OWNER_PASSWORD=$(hex 20)
LMS_APP_PASSWORD=$(hex 20)
KEYCLOAK_DB_PASSWORD=$(hex 20)
KEYCLOAK_ADMIN_PASSWORD=$(hex 20)
LMS_WEB_CLIENT_SECRET=$(hex 20)
LMS_ADMIN_CLIENT_SECRET=$(hex 20)
LMS_API_CLIENT_SECRET=$(hex 20)

# Garage: the RPC secret must be 32 bytes of hex; access key IDs are "GK" + 12 bytes of hex.
GARAGE_RPC_SECRET=$(hex 32)
GARAGE_ADMIN_TOKEN=$(hex 32)
S3_ACCESS_KEY_ID=GK$(hex 12)
S3_SECRET_ACCESS_KEY=$(hex 32)
ENV

echo "Wrote $OUT"
echo "Keycloak admin (admin console, home network only): user 'admin', password = KEYCLOAK_ADMIN_PASSWORD in that file."
